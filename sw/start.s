# =============================================================================
# 文字段初始化 (Text Segment Initialization)
# 功能：定義程式入口點，初始化系統環境
# =============================================================================

.section .text.init          # 定義初始化程式碼段
.globl _start                # 將 _start 標籤宣告為全域符號，可供連結器使用
.align 2                     # 確保 4 位元組對齊（2^2 = 4 位元組）

# =============================================================================
# 系統啟動入口點 (System Entry Point)
# 這是處理器重置後執行的第一段程式碼
# =============================================================================

_start:
    # ========================================================================
    # 步驟 1: 初始化堆疊指標 (Stack Pointer Initialization)
    # ------------------------------------------------------------------------
    # 堆疊是暫存函數呼叫的返回地址、局部變數和暫存器的記憶體區域
    # 使用連結腳本中定義的 _stack_top 符號，確保堆疊從記憶體頂部向下生長
    # ========================================================================
    la sp, _stack_top        # 載入堆疊頂部地址到堆疊指標暫存器 (sp)
    
    # ========================================================================
    # 步驟 2: 複製 .data 段從 ROM 到 RAM (Copy .data Section from ROM to RAM)
    # ------------------------------------------------------------------------
    # 連結腳本中定義了兩個關鍵符號：
    #   _data_lma_start: 資料在 ROM 中的位置 (Load Memory Address)
    #   _data_vma_start: 資料在 RAM 中的目標位置 (Virtual Memory Address)
    #   _data_vma_end:   資料在 RAM 中的結束位置
    # 
    # 在嵌入式系統中，初始化的全域變數通常儲存在 ROM 中，啟動時需要複製到 RAM
    # ========================================================================
    la t0, _data_lma_start   # t0 = ROM 中 .data 段的起始地址
    la t1, _data_vma_start   # t1 = RAM 中 .data 段的目標地址
    la t2, _data_vma_end     # t2 = RAM 中 .data 段的結束地址
    
    # 檢查 .data 段是否為空（起始地址等於結束地址）
    beq t1, t2, copy_data_done  # 如果相等，跳過複製過程
    
copy_data_loop:
    # 複製一個 32 位元組的資料
    lw t3, 0(t0)             # 從 ROM (t0) 讀取一個字 (32-bit) 到 t3
    sw t3, 0(t1)             # 將 t3 寫入 RAM (t1)
    
    # 移動到下一個位置
    addi t0, t0, 4           # ROM 指針向前移動 4 位元組
    addi t1, t1, 4           # RAM 指針向前移動 4 位元組
    
    # 檢查是否到達結束地址
    blt t1, t2, copy_data_loop  # 如果 t1 < t2，繼續迴圈
    
copy_data_done:
    
    # ========================================================================
    # 步驟 3: 清零 .bss 段 (Zero-initialize .bss Section)
    # ------------------------------------------------------------------------
    # .bss 段包含未初始化的全域和靜態變數，啟動時需要清零
    # 連結腳本定義了兩個符號：
    #   _bss_start: .bss 段的起始地址
    #   _bss_end:   .bss 段的結束地址
    # ========================================================================
    la t0, _bss_start        # t0 = .bss 段的起始地址
    la t1, _bss_end          # t1 = .bss 段的結束地址
    
    # 檢查 .bss 段是否為空
    beq t0, t1, clear_bss_done  # 如果相等，跳過清零過程
    
clear_bss_loop:
    sw zero, 0(t0)           # 將 0 寫入 t0 指向的地址
    addi t0, t0, 4           # 指針向前移動 4 位元組
    blt t0, t1, clear_bss_loop  # 如果 t0 < t1，繼續迴圈
    
clear_bss_done:
    
    # ========================================================================
    # 步驟 4: 清除超級使用者暫存暫存器 (Clear Supervisor Scratch Register)
    # ------------------------------------------------------------------------
    # sscratch 暫存器用於暫存資訊，啟動時清零是良好習慣
    # 雖然我們在機器模式下執行，但清除它可以避免潛在的錯誤
    # ========================================================================
    csrw sscratch, x0        # 將 0 寫入 sscratch 暫存器
    
    # ========================================================================
    # 步驟 5: 設定中斷向量表 (Set Interrupt Vector Table)
    # ------------------------------------------------------------------------
    # mtvec (Machine Trap-Vector Base-Address Register) 用於指定例外處理程式的入口地址
    # 當例外或中斷發生時，處理器會跳轉到此地址執行例外處理程式
    # ========================================================================
    la t0, exception_entry   # 載入例外處理程式的入口地址
    csrw mtvec, t0           # 將地址寫入 mtvec 暫存器
    
    # ========================================================================
    # 步驟 6: 設定機器模式狀態暫存器 (Set Machine Status Register)
    # ------------------------------------------------------------------------
    # mstatus 暫存器控制處理器的全域狀態，包括：
    #   - 中斷使能位 (MIE)
    #   - 前一個特權模式 (MPP)
    # 值 0x1800 設定 MPP=11 (機器模式)，並禁用中斷
    # ========================================================================
    li t0, 0x1800            # 載入狀態值到 t0
    csrw mstatus, t0         # 設定 mstatus 暫存器
    
    # ========================================================================
    # 步驟 7: 呼叫 C 語言主函數 (Call C Language Main Function)
    # ------------------------------------------------------------------------
    # jal (Jump and Link) 指令跳轉到 main 函數，並將返回地址儲存在 ra 暫存器
    # 此時系統環境已準備好，可以開始執行應用程式
    # ========================================================================
    jal ra, main             # 跳轉到 main 函數，保存返回地址到 ra
    
    # ========================================================================
    # 步驟 8: 安全防護 - 無窮迴圈 (Safety Guard - Infinite Loop)
    # ------------------------------------------------------------------------
    # 如果 main 函數返回（正常情況下不應該），進入無窮迴圈防止執行未定義程式碼
    # 這是一個安全措施，防止處理器執行隨機記憶體內容
    # ========================================================================
1:  j 1b                     # 無條件跳轉到標籤 1 (backwards)，形成無窮迴圈

# =============================================================================
# 例外向量表區段 (Exception Vector Table Section)
# 功能：處理所有例外和中斷事件
# =============================================================================

.section .text.vec          # 定義例外處理程式碼段
.align 2                    # 確保 4 位元組對齊
.global exception_entry     # 將 exception_entry 宣告為全域符號

# =============================================================================
# 例外處理程式入口點 (Exception Handler Entry Point)
# 當例外或中斷發生時，處理器自動跳轉到此處執行
# =============================================================================

exception_entry:
    # ========================================================================
    # 關鍵修正：加入 NOP 防止流水線危險 (Pipeline Hazard Prevention)
    # ------------------------------------------------------------------------
    # 問題：如果 addi sp 的結果未及時傳遞給後續的 sw 指令，sw 可能寫入錯誤的堆疊位置
    # 解決：在修改堆疊指標後插入 NOP，確保結果已傳遞
    # ========================================================================
    
    # ========================================================================
    # 子步驟 1: 立即禁用中斷，防止嵌套例外 (Disable Interrupts Immediately)
    # ------------------------------------------------------------------------
    # 在處理當前例外時，需要防止更高優先級的中斷發生，避免堆疊溢出和狀態混亂
    # mstatus 的 bit 3 是 MIE (Machine Interrupt Enable) 位元
    # ========================================================================
    csrr t0, mstatus        # 讀取當前 mstatus 值到 t0
    li t1, ~(1 << 3)        # 建立遮罩：清除第 3 位 (MIE)
    and t0, t0, t1          # 清除 MIE 位元，禁用中斷
    csrw mstatus, t0        # 寫回 mstatus 暫存器
    
    # ========================================================================
    # 子步驟 2: 保存除錯資訊到固定地址 (Save Debug Info to Fixed Address)
    # ------------------------------------------------------------------------
    # 將關鍵的例外資訊儲存到固定地址 (0x00018000)，便於除錯器讀取
    # 這是一種非侵入式的除錯方法，不影響正常例外處理流程
    # ========================================================================
    li t2, 0x00038000       # t2 = 除錯資訊儲存地址
    csrr t3, mepc           # 讀取發生例外時的程式計數器值
    sw t3, 0(t2)            # 儲存 mepc 到地址 0x00018000
    csrr t3, mcause         # 讀取例外原因暫存器
    sw t3, 4(t2)            # 儲存 mcause 到地址 0x00018004
    
    # ========================================================================
    # 子步驟 3: 分配堆疊空間 (Allocate Stack Space)
    # ------------------------------------------------------------------------
    # 為例外處理分配 128 位元組的堆疊空間，用於保存暫存器上下文
    # 在 RISC-V 中，堆疊是向下生長的，所以使用減法
    # ========================================================================
    addi sp, sp, -128       # 堆疊指標向下移動 128 位元組
    
    # ========================================================================
    # 子步驟 4: 插入 NOP 防止流水線危險 (Insert NOPs for Pipeline Safety)
    # ------------------------------------------------------------------------
    # 確保堆疊指標的更新已傳遞給後續指令，避免寫入錯誤的堆疊位置
    # 在簡單的處理器實現中，可能需要多個週期才能完成地址計算
    # ========================================================================
    nop                     # 無操作，等待一個週期
    nop                     # 無操作，等待一個週期
    nop                     # 無操作，等待一個週期
    
    # ========================================================================
    # 子步驟 5: 保存關鍵暫存器到堆疊 (Save Critical Registers to Stack)
    # ------------------------------------------------------------------------
    # 保存所有可能被 C 語言函數修改的暫存器，以便例外處理後能恢復原始狀態
    # RISC-V 暫存器約定：
    #   ra: 返回地址暫存器 (最重要！)
    #   t0-t6: 臨時暫存器
    #   a0-a7: 函數參數/返回值暫存器
    #   s0-s11: 保存暫存器
    #   gp: 全域指針，tp: 執行緒指針
    # ========================================================================
    sw ra, 0(sp)            # [關鍵] 保存被中斷函式的返回地址
    sw t0, 4(sp)            # 保存 t0
    sw t1, 8(sp)            # 保存 t1
    sw t2, 12(sp)           # 保存 t2
    sw a0, 16(sp)           # 保存 a0
    sw a1, 20(sp)           # 保存 a1
    sw a2, 24(sp)           # 保存 a2
    sw a3, 28(sp)           # 保存 a3
    sw a4, 32(sp)           # 保存 a4
    sw a5, 36(sp)           # 保存 a5
    sw a6, 40(sp)           # 保存 a6
    sw a7, 44(sp)           # 保存 a7
    sw t3, 48(sp)           # 保存 t3
    sw t4, 52(sp)           # 保存 t4
    sw t5, 56(sp)           # 保存 t5
    sw t6, 60(sp)           # 保存 t6
    sw s0, 64(sp)           # 保存 s0
    sw s1, 68(sp)           # 保存 s1
    sw s2, 72(sp)           # 保存 s2
    sw s3, 76(sp)           # 保存 s3
    sw s4, 80(sp)           # 保存 s4
    sw s5, 84(sp)           # 保存 s5
    sw s6, 88(sp)           # 保存 s6
    sw s7, 92(sp)           # 保存 s7
    sw s8, 96(sp)           # 保存 s8
    sw s9, 100(sp)          # 保存 s9
    sw s10, 104(sp)         # 保存 s10
    sw s11, 108(sp)         # 保存 s11
    sw gp, 112(sp)          # 保存全域指針
    sw tp, 116(sp)          # 保存執行緒指針
    
    # ========================================================================
    # 子步驟 6: 保存例外相關暫存器 (Save Exception-related Registers)
    # ------------------------------------------------------------------------
    # mepc: 例外發生時的程式計數器值（返回地址）
    # mcause: 例外原因（判斷是例外還是中斷，以及具體類型）
    # 這些值儲存在堆疊的最後兩個位置
    # ========================================================================
    csrr t0, mepc           # 讀取 mepc 暫存器
    sw t0, 120(sp)          # 儲存 mepc 到堆疊偏移 120
    csrr t0, mcause         # 讀取 mcause 暫存器
    sw t0, 124(sp)          # 儲存 mcause 到堆疊偏移 124
    
    # ========================================================================
    # 子步驟 7: 準備 C 函數參數 (Prepare C Function Parameters)
    # ------------------------------------------------------------------------
    # 呼叫 C 語言例外處理函數 handle_exception，需要三個參數：
    #   a0: 例外原因 (mcause)
    #   a1: 例外發生地址 (mepc)
    #   a2: 堆疊指針（指向保存的暫存器上下文）
    # 按照 RISC-V 呼叫約定，參數通過 a0-a7 暫存器傳遞
    # ========================================================================
    lw a0, 124(sp)          # a0 = 例外原因 (mcause)
    lw a1, 120(sp)          # a1 = 例外發生地址 (mepc)
    mv a2, sp               # a2 = 堆疊指針（上下文地址）
    
    # ========================================================================
    # 子步驟 8: 呼叫 C 語言例外處理函數 (Call C Exception Handler)
    # ------------------------------------------------------------------------
    # handle_exception 函數用於：
    #   1. 根據例外原因執行相應處理
    #   2. 更新 mepc（如需要跳過故障指令）
    #   3. 進行除錯輸出
    #   4. 處理中斷請求
    # ========================================================================
    jal ra, handle_exception  # 跳轉到 C 語言處理函數
    
    # ========================================================================
    # 子步驟 9: 恢復例外返回地址 (Restore Exception Return Address)
    # ------------------------------------------------------------------------
    # 從堆疊中恢復 mepc，C 函數可能修改了它（例如跳過故障指令）
    # mepc 決定了 mret 指令執行後返回的地址
    # ========================================================================
    lw t0, 120(sp)          # 從堆疊讀取 mepc 值
    csrw mepc, t0           # 恢復 mepc 暫存器
    
    # ========================================================================
    # 子步驟 10: 恢復暫存器上下文 (Restore Register Context)
    # ------------------------------------------------------------------------
    # 按照與保存相反的順序恢復所有暫存器
    # 注意：ra 暫存器必須最後恢復，因為它是返回地址
    # ========================================================================
    lw ra, 0(sp)            # [關鍵] 恢復被中斷函式的返回地址
    
    # 恢復其他暫存器
    lw t0, 4(sp)            # 恢復 t0
    lw t1, 8(sp)            # 恢復 t1
    lw t2, 12(sp)           # 恢復 t2
    lw a0, 16(sp)           # 恢復 a0
    lw a1, 20(sp)           # 恢復 a1
    lw a2, 24(sp)           # 恢復 a2
    lw a3, 28(sp)           # 恢復 a3
    lw a4, 32(sp)           # 恢復 a4
    lw a5, 36(sp)           # 恢復 a5
    lw a6, 40(sp)           # 恢復 a6
    lw a7, 44(sp)           # 恢復 a7
    lw t3, 48(sp)           # 恢復 t3
    lw t4, 52(sp)           # 恢復 t4
    lw t5, 56(sp)           # 恢復 t5
    lw t6, 60(sp)           # 恢復 t6
    lw s0, 64(sp)           # 恢復 s0
    lw s1, 68(sp)           # 恢復 s1
    lw s2, 72(sp)           # 恢復 s2
    lw s3, 76(sp)           # 恢復 s3
    lw s4, 80(sp)           # 恢復 s4
    lw s5, 84(sp)           # 恢復 s5
    lw s6, 88(sp)           # 恢復 s6
    lw s7, 92(sp)           # 恢復 s7
    lw s8, 96(sp)           # 恢復 s8
    lw s9, 100(sp)          # 恢復 s9
    lw s10, 104(sp)         # 恢復 s10
    lw s11, 108(sp)         # 恢復 s11
    lw gp, 112(sp)          # 恢復全域指針
    lw tp, 116(sp)          # 恢復執行緒指針
    
    # ========================================================================
    # 子步驟 11: 釋放堆疊空間 (Deallocate Stack Space)
    # ------------------------------------------------------------------------
    # 將堆疊指標恢復到例外發生前的位置
    # 同樣插入 NOP 防止流水線危險
    # ========================================================================
    addi sp, sp, 128        # 堆疊指標向上移動 128 位元組
    nop                     # 無操作，等待一個週期
    nop                     # 無操作，等待一個週期
    
    # ========================================================================
    # 子步驟 12: 從例外返回 (Return from Exception)
    # ------------------------------------------------------------------------
    # mret 指令執行以下操作：
    #   1. 從 mepc 載入程式計數器
    #   2. 根據 mstatus 恢復中斷狀態
    #   3. 恢復特權模式
    # 執行後，處理器繼續從例外發生處（或修改後的地址）執行
    # ========================================================================
    mret                    # 從機器模式例外返回
    
# =============================================================================
# 純組合語言測試函數 (Pure Assembly Test Function)
# 功能：用於測試和除錯組合語言指令
# =============================================================================

.global test_asm_only       # 宣告為全域符號，可供 C 語言呼叫
test_asm_only:
    # ========================================================================
    # 測試組合語言指令序列
    # ------------------------------------------------------------------------
    # 這個函數展示了基本的組合語言操作：
    #   1. 儲存返回地址到固定位置
    #   2. 執行一些操作
    #   3. 恢復返回地址
    #   4. 返回呼叫者
    # ========================================================================
    li t0, 0x00018000       # 載入測試地址到 t0
    sw ra, 0(t0)            # 保存當前返回地址到測試地址
    
    nop                     # 無操作指令，用於測試流水線
    
    addi x0, x0, 0          # 對 x0 執行加法（無效果，x0 永遠為 0）
                            # 這是一個常見的 NOP 替代方式
    
    sw ra, 4(t0)            # 再次保存返回地址（測試目的）
    
    lw ra, 0(t0)            # 從測試地址恢復返回地址
    
    ret                     # 返回呼叫者（等價於 jalr x0, ra, 0）
    